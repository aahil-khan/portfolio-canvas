// prototype/lab/night-mode/render-sample.mjs: renders the narration sample, offline, with SAM.
//
//   node prototype/lab/night-mode/render-sample.mjs
//
// One section of one post: the introduction of "The Laptop That Became My Cloud". Its words are
// read from the same essay the reader shows (essay.js), rendered a word at a time with SAM
// (sam.js, logic.samWords), and written as two files beside the page:
//   narration/sample-audio.js    the WAV (8-bit mono, 11 025 Hz), base64, as NIGHT.narrationWav
//   narration/sample-timings.js  each word's start and end, and the waveform's peaks, as NIGHT.narration
// They are wrapped in scripts only so the mockup works from file://, where fetch() and a media
// element's samples are both refused. The real build commits a plain MP3 and a JSON timings file
// (public/audio/, research ★5A), made in the same publish-time Action as the "now" summary.
// No paid service, no network: SAM runs here, in Node.
import { createRequire } from 'node:module'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
globalThis.window = globalThis
for (const f of ['../shared/pieces.js', '../shared/body.js', 'work.js', 'copy.js', 'essay.js', 'model.js', 'logic.js']) require(join(here, f))
const SamJs = require(join(here, 'sam.js'))
const { LAB, NIGHT } = globalThis
const M = NIGHT.model, G = NIGHT.logic

export const SAMPLE = { slug: 'old-laptop-cloud', section: 'introduction-the-laptop-that-became-my-cloud', voice: { speed: 72, pitch: 64, mouth: 128, throat: 128 } }

// the words a reader sees: markdown marks gone, figures and subheadings skipped
export const plain = (block) => block.replace(/!\[[^\]]*\]\([^)]*\)/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/\[\[([a-z0-9-]+)\]\]/g, '$1')
  .replace(/\*\*|\*|`/g, '').replace(/^\s*(?:-|\d+\.)\s+/gm, '').trim()
export function sampleWords() {
  const p = LAB.pieces.find((x) => x.slug === SAMPLE.slug)
  const sec = M.parts(M.bodyOf(p)).find((s) => s.id === SAMPLE.section)
  const text = sec.blocks.filter((b) => !/^(!\[|###?\s)/.test(b.trim())).map(plain).filter(Boolean).join('\n')
  return { title: sec.title, words: G.tokens(text).map((t) => t.w) }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { title, words } = sampleWords()
  const r = G.samWords(SamJs, words, SAMPLE.voice)
  const samples = G.half(r.samples), sr = r.sr / 2
  const perSec = 20
  const out = {
    slug: SAMPLE.slug, section: SAMPLE.section, title, voice: 'sam', settings: SAMPLE.voice, sr, dur: r.dur, perSec,
    peaks: G.peaks(samples, sr, perSec), words: r.words,
  }
  mkdirSync(join(here, 'narration'), { recursive: true })
  const banner = (what) => `// GENERATED by render-sample.mjs (SAM, offline): ${what}. Do not edit; run the script again.\n`
  writeFileSync(join(here, 'narration/sample-timings.js'), banner(`"${title}", ${words.length} words, ${r.dur} s`) + `;(window.NIGHT = window.NIGHT || {}).narration = ${JSON.stringify(out)}\n`)
  writeFileSync(join(here, 'narration/sample-audio.js'), banner(`the WAV, ${sr} Hz 8-bit mono, base64`) + `;(window.NIGHT = window.NIGHT || {}).narrationWav = '${G.b64(G.wav8(samples, sr))}'\n`)
  console.log(`rendered "${title}": ${words.length} words, ${r.dur} s, ${Math.round(samples.length / 1024)} KB of samples`)
}
