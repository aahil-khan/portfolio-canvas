// prototype/lab/notebook/tools/build-vault.mjs: notes/**.md → vault.js, so the page works over file://
//
//   node prototype/lab/notebook/tools/build-vault.mjs [--check]
//
// vault.js holds every note's file exactly as written, keyed by its path under notes/. model.js
// does the parsing, in the browser and in check.mjs alike, so there is one parser. --check writes
// nothing and exits 1 if vault.js is not byte-identical to a fresh run.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const NOTES = join(here, '..', 'notes'), OUT = join(here, '..', 'vault.js')
const walk = (d) => readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : e.name.endsWith('.md') ? [join(d, e.name)] : []))

export function render() {
  const files = Object.fromEntries(walk(NOTES).map((f) => [relative(NOTES, f).split('\\').join('/'), readFileSync(f, 'utf8')]))
  return `/*
 * prototype/lab/notebook/vault.js: GENERATED by tools/build-vault.mjs from notes/**.md. Do not edit:
 * edit the notes, then run the builder. ${Object.keys(files).length} files.
 */
;(() => {
  const root_ = typeof window !== 'undefined' ? window : globalThis
  const NB = (root_.NB = root_.NB || {})
  NB.vaultFiles = ${JSON.stringify(files, null, 1)}
})()
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const js = render()
  if (process.argv.includes('--check')) {
    const same = existsSync(OUT) && readFileSync(OUT, 'utf8') === js
    console.log(same ? 'vault.js is current' : 'vault.js is STALE: run tools/build-vault.mjs')
    process.exit(same ? 0 : 1)
  }
  writeFileSync(OUT, js)
  console.log(`vault.js: ${js.length} bytes`)
}
