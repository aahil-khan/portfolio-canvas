// prototype/lab/notebook/tools/build-seed.mjs: a cold layout of the vault → graph-seed.js
//
//   node prototype/lab/notebook/tools/build-seed.mjs
//
// Run it when the vault changes a lot. Day to day the page starts warm from the committed seed,
// so a new note settles in place and the rest stay where readers last saw them.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const here = dirname(fileURLToPath(import.meta.url)), dir = join(here, '..')
const require = createRequire(import.meta.url)
for (const f of ['copy.js', 'md.js', 'model.js', 'graph.js', 'vault.js', 'study.js', 'essay.js']) require(join(dir, f))
const NB = globalThis.NB
export const graphInput = (v) => ({
  nodes: v.notes.map((n) => ({ key: n.route, section: n.section, type: n.type })),
  edges: v.edges.map((e) => ({ a: e.a.route, b: e.b.route, kind: e.kind })),
})
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const v = NB.model.build({ files: NB.vaultFiles, study: NB.study, essays: globalThis.NIGHT.imports, copy: NB.copy })
  const { nodes, edges } = graphInput(v)
  const { pos } = NB.graph.layout(nodes, edges)
  writeFileSync(join(dir, 'graph-seed.js'), `/*
 * prototype/lab/notebook/graph-seed.js: GENERATED by tools/build-seed.mjs, a cold layout of the
 * vault. The page starts warm from here, so adding a note barely moves the others.
 */
;(() => {
  const root_ = typeof window !== 'undefined' ? window : globalThis
  const NB = (root_.NB = root_.NB || {})
  NB.graphSeed = ${JSON.stringify(pos)}
})()
`)
  console.log(`graph-seed.js: ${nodes.length} nodes, ${edges.length} edges`)
}
